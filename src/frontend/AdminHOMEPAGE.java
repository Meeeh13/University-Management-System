    public void loadFacultyTable() {
    try (Connection conn = DriverManager.getConnection("jdbc:sqlite:UMSdatabase.db");
         PreparedStatement pst = conn.prepareStatement("SELECT * FROM students_faculty")) {

        ResultSet rs = pst.executeQuery();
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("name"),
                rs.getString("id"),
                rs.getString("email"),
                rs.getString("birth_date"),
                rs.getString("address")
            });
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error loading table: " + e.getMessage());
    }
}

    



